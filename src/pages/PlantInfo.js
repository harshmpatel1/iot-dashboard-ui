const EnvironmentalBenefits = ({ lifetimeGenerationMWh, pdata, data, unit }) => {
  // console.log("lifetimeGenerationMWh",lifetimeGenerationMWh)
  // console.log("pdata",pdata)

  // console.log("data",data)
  //   console.log("unit",unit)




  // console.log('Calculating benefits for Lifetime Generation (MWh):', lifetimeGenerationMWh);
  // Calculate all benefit metrics based on the lifetime generation
  const benefits = useMemo(() => {
    // Ensure the generation value is valid before calculating
    if (lifetimeGenerationMWh <= 0) {
      return [];
    }

    // Perform the calculations
    const coalSaved = lifetimeGenerationMWh * CONVERSION_FACTORS.COAL_SAVED_T_PER_MWH;
    const co2Reduced = lifetimeGenerationMWh * CONVERSION_FACTORS.CO2_REDUCED_T_PER_MWH;
    const treesPlanted = lifetimeGenerationMWh * CONVERSION_FACTORS.TREES_PLANTED_PER_MWH;
    const price = pdata?.UnitPrice > 0 ? pdata?.UnitPrice : 5;

    const totalYields =
      unit === "MWh"
        ? price * 1000 * data?.LifetimeGeneration
        : price * data?.LifetimeGeneration;
    // Define the data structure for rendering
    return [
      {
        icon: Package,
        title: "Standard Coal Saved",
        value: coalSaved.toFixed(2),
        unit: "t",
        color: "text-blue-500",
      },
      {
        icon: CloudOff,
        title: "CO₂ Emission Reduction",
        value: co2Reduced.toFixed(2),
        unit: "t",
        color: "text-green-500",
      },
      {
        icon: Leaf,
        title: "Trees Planted (Equivalent)",
        value: treesPlanted.toFixed(0).toLocaleString(), // Trees are usually displayed as whole numbers
        unit: "Trees",
        color: "text-yellow-600",
      },
      {
        icon: IndianRupee,
        title: "Total Yields (Economic)",
        value: parseInt(totalYields.toFixed(2)).toLocaleString(),
        unit: "INR",
        color: "text-indigo-500",
      },
    ];
  }, [lifetimeGenerationMWh]);

  return (
    <div className="shadow-md rounded-3xl p-5 mx-auto font-sans  w-full h-full">

      {/* Title Bar */}
      <div className="flex items-center justify-between border-b pb-4 mb-6">

        <HelpCircle className="w-5 h-5 text-gray-400 cursor-help" title="Based on Standard Industry Conversion Factors" />
      </div>

      {/* Lifetime Generation Display (from the user's original snippet) */}


      {/* Benefits Grid */}
      {lifetimeGenerationMWh > 0 ? (
        <div className="flex flex-col gap-2">
          {benefits.map((benefit) => (
            <BenefitMetric key={benefit.title} {...benefit} />
          ))}
        </div>
      ) : (
        <div className="text-center p-12 bg-white rounded-xl shadow-inner text-gray-500">
          No lifetime generation data available yet to calculate benefits.
        </div>
      )}
    </div>
  );
};

